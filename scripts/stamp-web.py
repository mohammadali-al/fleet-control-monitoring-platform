#!/usr/bin/env python3
"""stamp-web.py - DEV-ONLY page generator for the static panel front-end.

Why: the panel shell (icon sprite, sidebar, top bar) must be identical in every page, but plain
static HTML on file:// cannot include a partial. This script stamps every page from ONE shell, so
the shell cannot drift across files. The committed output (web/*.html) is plain static HTML that
works from file:// with no tooling. Nothing here ships or runs at runtime.

Sources (edit these, never the generated pages):
  web/_src/shell.html        the layout: head, icon sprite, sidebar, top bar, <main>{{content}}</main>
  web/_src/pages/<name>.html one fragment per page; first line must be  <!-- title: Page title -->

Shell placeholders:
  {{title}}        page title (from the fragment's first line)
  {{content}}      the fragment body
  {{aria:<page>}}  becomes ' aria-current="page"' on the nav link of the page being stamped

Fragment macros (expanded in fragments only):
  {{i:name}} / {{i:name:sm}}   inline SVG icon from the sprite
  {{state:online|reconnecting|offline}}   machine state chip
  {{role:worker|monitor}}                 role chip

Usage:
  python3 scripts/stamp-web.py           regenerate web/<page>.html for every fragment
  python3 scripts/stamp-web.py --check   exit 1 if any generated page is out of date (no writes)

Stdlib only. In the Go port, shell.html becomes the layout template and fragments become {{define "content"}}.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
SRC = WEB / "_src"
BANNER = ("<!-- GENERATED by scripts/stamp-web.py from web/_src/shell.html and "
          "web/_src/pages/{name}.html. Edit those, not this file. -->\n")

STATES = {
    "online": ("ok", "check", "Online"),
    "reconnecting": ("warn", "refresh", "Reconnecting"),
    "offline": ("danger", "x", "Offline"),
}
ROLES = {
    "worker": ("accent", "Worker agent"),
    "monitor": ("info", "Monitor agent"),
}


def icon(name, size=""):
    cls = "icon icon--sm" if size == "sm" else "icon"
    return f'<svg class="{cls}" aria-hidden="true"><use href="#i-{name}"/></svg>'


def expand_macros(text):
    text = re.sub(r"\{\{i:([a-z0-9-]+)(?::(sm))?\}\}", lambda m: icon(m.group(1), m.group(2) or ""), text)

    def state(m):
        tone, ic, label = STATES[m.group(1)]
        return f'<span class="chip chip--{tone}">{icon(ic)}{label}</span>'

    def role(m):
        tone, label = ROLES[m.group(1)]
        return f'<span class="chip chip--{tone}">{label}</span>'

    text = re.sub(r"\{\{state:(online|reconnecting|offline)\}\}", state, text)
    text = re.sub(r"\{\{role:(worker|monitor)\}\}", role, text)
    return text


def stamp(name, shell, fragment):
    first, _, body = fragment.partition("\n")
    m = re.match(r"<!--\s*title:\s*(.+?)\s*-->", first)
    if not m:
        raise SystemExit(f"{name}.html: first line must be <!-- title: ... -->")
    out = shell.replace("{{title}}", m.group(1))
    out = out.replace("{{content}}", expand_macros(body.strip("\n")))
    out = re.sub(r"\{\{aria:([a-z]+)\}\}", lambda a: ' aria-current="page"' if a.group(1) == name else "", out)
    left = re.findall(r"\{\{[^}]+\}\}", out)
    if left:
        raise SystemExit(f"{name}.html: unresolved placeholders {left}")
    # banner goes right after the doctype so the page still starts with <!doctype html>
    doctype, _, rest = out.partition("\n")
    return doctype + "\n" + BANNER.format(name=name) + rest


def main():
    check = "--check" in sys.argv[1:]
    shell = (SRC / "shell.html").read_text(encoding="utf-8")
    stale = []
    for frag in sorted((SRC / "pages").glob("*.html")):
        name = frag.stem
        html = stamp(name, shell, frag.read_text(encoding="utf-8"))
        target = WEB / f"{name}.html"
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != html:
            stale.append(name)
            if not check:
                target.write_text(html, encoding="utf-8")
    if check:
        if stale:
            print("out of date: " + ", ".join(stale) + "  (run scripts/stamp-web.py)")
            return 1
        print("web pages are up to date")
        return 0
    print("stamped: " + (", ".join(stale) if stale else "nothing to do"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
